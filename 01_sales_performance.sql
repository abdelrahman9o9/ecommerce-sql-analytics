WITH
	ORDERS_CTE AS (
		SELECT
			COUNT(*) AS TOTAL_ORDERS,
			COUNT(*) FILTER (
				WHERE
					STATUS = 'cancelled'
			) AS CANCELLED_ORDERS,
			COUNT(*) FILTER (
				WHERE
					STATUS != 'cancelled'
			) AS VALID_ORDERS
		FROM
			ECOMMERCE.ORDERS
	),
	SALES_CTE AS (
		SELECT
			SUM(EOI.QUANTITY * EOI.UNIT_PRICE) AS TOTAL_ORDER_VALUE,
			SUM(EOI.QUANTITY * EOI.UNIT_PRICE) FILTER (
				WHERE
					EO.STATUS != 'cancelled'
			) AS VALID_SALES_VALUE,
			SUM(EOI.QUANTITY * EOI.UNIT_PRICE) FILTER (
				WHERE
					EO.STATUS != 'cancelled'
			) / COUNT(DISTINCT EO.ORDER_ID) FILTER (
				WHERE
					EO.STATUS != 'cancelled'
			) AS AVERAGE_ORDER_VALUE
		FROM
			ECOMMERCE.ORDER_ITEMS AS EOI
			JOIN ECOMMERCE.ORDERS AS EO ON EOI.ORDER_ID = EO.ORDER_ID
	),
	PAYMENTS_CTE AS (
		SELECT
			SUM(AMOUNT) FILTER (
				WHERE
					PAYMENT_STATUS = 'paid'
			) AS PAID_REVENUE,
			SUM(AMOUNT) FILTER (
				WHERE
					PAYMENT_STATUS = 'pending'
			) AS PENDING_PAYMENT_VALUE,
			SUM(AMOUNT) FILTER (
				WHERE
					PAYMENT_STATUS = 'failed'
			) AS FAILED_PAYMENT_VALUE
		FROM
			ECOMMERCE.PAYMENTS
	)
SELECT
	*
FROM
	ORDERS_CTE
	CROSS JOIN SALES_CTE
	CROSS JOIN PAYMENTS_CTE;